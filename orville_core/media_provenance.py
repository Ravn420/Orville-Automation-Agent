class MediaProvenanceStore:
    """Persist media lineage under a bounded, repository-owned directory.

    Source and generated files are copied into the store; the caller's original
    files are never modified. Prompt text is redacted before persistence while a
    SHA-256 digest preserves reproducibility checks without retaining secrets.

    This enhanced version supports:
    - Generation metadata tracking (prompt, model, parameters, timestamp)
    - Licensing state management (open source, proprietary, custom)
    - Rights verification workflows
    - Provenance chain/lineage tracking
    - Export/import of provenance records
    - Integration with media_generation provenance hooks
    - Cryptographic verification for provenance integrity
    """

    def __init__(
        self,
        root: str | Path,
        *,
        max_asset_bytes: int = _MAX_ASSET_BYTES,
        signing_key: str | None = None,
    ) -> None:
        self.root = Path(root).expanduser().resolve()
        self.assets_root = self.root / "assets"
        self.history_path = self.root / "history.json"
        self.licenses_path = self.root / "licenses.json"
        self.rights_path = self.root / "rights.json"
        self.assets_root.mkdir(parents=True, exist_ok=True)
        self.policy = FilesystemPolicy((self.root,), allow_write=True)
        if max_asset_bytes < 1:
            raise ValueError("max_asset_bytes must be positive")
        self.max_asset_bytes = max_asset_bytes
        self._signing_key = signing_key or secrets.token_hex(32)
        self._rights_cache: dict[str, RightsVerification] = {}
        self._license_cache: dict[str, LicenseTerms] = {}

    def ingest_asset(
        self,
        path: str | Path,
        *,
        role: str,
        asset_id: str | None = None,
        generation_metadata: GenerationMetadata | None = None,
        license_terms: LicenseTerms | None = None,
        parent_asset_ids: tuple[str, ...] = (),
    ) -> MediaAsset:
        """Copy an asset into the store and return checksum-addressed metadata.

        Args:
            path: Path to the asset file
            role: Role of the asset (e.g., "source", "generated", "reference")
            asset_id: Optional custom asset ID
            generation_metadata: Metadata about how the asset was generated
            license_terms: License terms for the asset
            parent_asset_ids: IDs of parent assets (for derivative works)

        Returns:
            MediaAsset with complete provenance information
        """
        source = Path(path).expanduser().resolve()
        if not source.is_file():
            raise FileNotFoundError(source)
        size = source.stat().st_size
        if size > self.max_asset_bytes:
            raise ValueError(f"asset exceeds maximum size of {self.max_asset_bytes} bytes")
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        safe_role = self._safe_component(role, "source")
        safe_name = self._safe_component(source.name, "asset")
        target = self.assets_root / safe_role / f"{digest[:16]}-{safe_name}"
        self.policy.resolve(target, write=True)
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            shutil.copy2(source, target)
        media_type = mimetypes.guess_type(source.name)[0] or "application/octet-stream"

        # Compute provenance chain hash
        previous_hash = None
        if parent_asset_ids:
            # Get the last parent's provenance hash for chaining
            parent_record = self._find_record_with_asset(parent_asset_ids[-1])
            if parent_record:
                previous_hash = parent_record.provenance_chain_hash

        asset = MediaAsset(
            asset_id=asset_id or digest[:16],
            role=role,
            name=source.name,
            relative_path=target.relative_to(self.root).as_posix(),
            media_type=media_type,
            size=size,
            sha256=digest,
            created_at=datetime.now(UTC).isoformat(),
            generation_metadata=generation_metadata,
            license_terms=license_terms,
            parent_asset_ids=parent_asset_ids,
        )

        # Compute and set the provenance chain hash
        provenance_hash = asset.compute_provenance_hash(previous_hash)
        # Create new asset with computed hash (dataclass is frozen)
        asset = MediaAsset(
            asset_id=asset.asset_id,
            role=asset.role,
            name=asset.name,
            relative_path=asset.relative_path,
            media_type=asset.media_type,
            size=asset.size,
            sha256=asset.sha256,
            created_at=asset.created_at,
            generation_metadata=asset.generation_metadata,
            license_terms=asset.license_terms,
            rights_verification=asset.rights_verification,
            parent_asset_ids=asset.parent_asset_ids,
            provenance_chain_hash=provenance_hash,
        )

        # Cache license if provided
        if license_terms:
            self._license_cache[asset.asset_id] = license_terms
            self._persist_licenses()

        return asset

    def _find_record_with_asset(self, asset_id: str) -> MediaHistoryRecord | None:
        """Find a history record containing the given asset ID."""
        for record in self.list_history():
            if asset_id in record.generated_asset_ids or asset_id in record.source_asset_ids:
                return record
        return None

    def record(
        self,
        *,
        prompt: str,
        source_assets: Iterable[MediaAsset],
        generated_assets: Iterable[MediaAsset],
        transformations: Iterable[MediaTransformation] = (),
        metadata: dict[str, Any] | None = None,
        history_id: str | None = None,
        generation_metadata: GenerationMetadata | None = None,
        license_terms: LicenseTerms | None = None,
        parent_history_ids: tuple[str, ...] = (),
    ) -> MediaHistoryRecord:
        """Append a redacted prompt and complete media lineage atomically.

        Args:
            prompt: The generation prompt (will be redacted for secrets)
            source_assets: Source/input assets used
            generated_assets: Assets that were generated
            transformations: Transformations applied
            metadata: Additional metadata
            history_id: Optional custom history ID
            generation_metadata: Detailed generation metadata
            license_terms: License terms for generated assets
            parent_history_ids: IDs of parent history records (for derivatives)

        Returns:
            MediaHistoryRecord with complete provenance
        """
        source = tuple(source_assets)
        generated = tuple(generated_assets)
        safe_prompt = str(SecretRedactor.redact(prompt))

        # Compute chain hash
        chain_data = {
            "prompt_sha256": hashlib.sha256(str(prompt).encode("utf-8")).hexdigest(),
            "source_asset_ids": [asset.asset_id for asset in source],
            "generated_asset_ids": [asset.asset_id for asset in generated],
            "transformations": [t.transformation_hash for t in transformations],
            "parent_history_ids": list(parent_history_ids),
        }
        if generation_metadata:
            chain_data["generation_hash"] = generation_metadata.compute_integrity_hash()
        chain_hash = hashlib.sha256(
            json.dumps(chain_data, sort_keys=True, ensure_ascii=False).encode("utf-8")
        ).hexdigest()

        # Sign the record
        signature = self._sign_record(chain_hash)

        record = MediaHistoryRecord(
            history_id=history_id or f"media-{uuid4().hex[:16]}",
            prompt=safe_prompt,
            prompt_sha256=hashlib.sha256(str(prompt).encode("utf-8")).hexdigest(),
            source_asset_ids=tuple(asset.asset_id for asset in source),
            generated_asset_ids=tuple(asset.asset_id for asset in generated),
            transformations=tuple(transformations),
            created_at=datetime.now(UTC).isoformat(),
            metadata=SecretRedactor.redact(dict(metadata or {})),
            generation_metadata=generation_metadata,
            license_terms=license_terms,
            provenance_chain_hash=chain_hash,
            parent_history_ids=parent_history_ids,
            signature=signature,
        )
        records = self.list_history()
        records.append(record)
        temporary = self.history_path.with_suffix(".json.tmp")
        temporary.write_text(
            json.dumps([item.to_dict() for item in records], indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8"
        )
        os.replace(temporary, self.history_path)

        # Persist license if provided
        if license_terms:
            for asset in generated:
                self._license_cache[asset.asset_id] = license_terms
            self._persist_licenses()

        return record

    def _sign_record(self, chain_hash: str) -> str:
        """Create a cryptographic signature for a record."""
        data = f"{chain_hash}:{datetime.now(UTC).isoformat()}"
        return hmac.new(
            self._signing_key.encode("utf-8"),
            data.encode("utf-8"),
            hashlib.sha256
        ).hexdigest()[:32]

    def verify_record(self, record: MediaHistoryRecord) -> bool:
        """Verify the integrity of a provenance record."""
        return record.verify_integrity()

    def list_history(self) -> list[MediaHistoryRecord]:
        """Load all preserved records, returning an empty history when absent."""
        if not self.history_path.exists():
            return []
        payload = json.loads(self.history_path.read_text(encoding="utf-8"))
        if not isinstance(payload, list):
            raise ValueError("media history must be a JSON list")
        return [MediaHistoryRecord.from_dict(item) for item in payload]

    def get_record(self, history_id: str) -> MediaHistoryRecord | None:
        """Get a specific history record by ID."""
        for record in self.list_history():
            if record.history_id == history_id:
                return record
        return None

    def get_asset_lineage(self, asset_id: str) -> list[MediaHistoryRecord]:
        """Get the complete lineage for an asset.

        Returns a list of records in chronological order showing
        the full provenance chain for the given asset.
        """
        lineage = []
        current_id = asset_id

        # Find the record containing this asset
        record = self._find_record_with_asset(current_id)
        while record:
            lineage.insert(0, record)
            # Follow parent history IDs
            if record.parent_history_ids:
                parent = self.get_record(record.parent_history_ids[-1])
                if parent and parent not in lineage:
                    record = parent
                else:
                    break
            else:
                break

        return lineage

    def get_derivative_assets(self, asset_id: str) -> list[str]:
        """Get all asset IDs that are derived from the given asset."""
        derivatives = []
        for record in self.list_history():
            if asset_id in record.source_asset_ids:
                derivatives.extend(record.generated_asset_ids)
        return derivatives

    def asset_path(self, asset: MediaAsset) -> Path:
        """Resolve a retained asset through the repository-boundary policy."""
        path = self.policy.resolve(self.root / asset.relative_path)
        if not path.is_file():
            raise FileNotFoundError(path)
        return path

    def get_asset(self, asset_id: str) -> MediaAsset | None:
        """Get a specific asset by ID from history records."""
        for record in self.list_history():
            # Check source assets
            for src_id in record.source_asset_ids:
                if src_id == asset_id:
                    # Try to load from license cache which has full asset info
                    if asset_id in self._license_cache:
                        # Reconstruct from available data
                        return self._reconstruct_asset(asset_id, record)
            # Check generated assets
            for gen_id in record.generated_asset_ids:
                if gen_id == asset_id:
                    return self._reconstruct_asset(asset_id, record)
        return None

    def _reconstruct_asset(self, asset_id: str, record: MediaHistoryRecord) -> MediaAsset | None:
        """Reconstruct asset information from record and caches."""
        # Look for the actual file in assets directory
        for role_dir in self.assets_root.iterdir():
            if role_dir.is_dir():
                for asset_file in role_dir.iterdir():
                    if asset_file.is_file() and asset_id in asset_file.name:
                        size = asset_file.stat().st_size
                        sha256 = hashlib.sha256(asset_file.read_bytes()).hexdigest()
                        media_type = mimetypes.guess_type(asset_file.name)[0] or "application/octet-stream"
                        return MediaAsset(
                            asset_id=asset_id,
                            role=role_dir.name,
                            name=asset_file.name.split("-", 1)[1] if "-" in asset_file.name else asset_file.name,
                            relative_path=asset_file.relative_to(self.root).as_posix(),
                            media_type=media_type,
                            size=size,
                            sha256=sha256,
                            created_at=datetime.fromtimestamp(asset_file.stat().st_mtime, UTC).isoformat(),
                            license_terms=self._license_cache.get(asset_id),
                        )
        return None

    # License and Rights Management

    def register_license(self, asset_id: str, license_terms: LicenseTerms) -> bool:
        """Register license terms for an asset."""
        self._license_cache[asset_id] = license_terms
        return self._persist_licenses()

    def get_license(self, asset_id: str) -> LicenseTerms | None:
        """Get license terms for an asset."""
        if asset_id in self._license_cache:
            return self._license_cache[asset_id]
        # Try to load from disk
        self._load_licenses()
        return self._license_cache.get(asset_id)

    def verify_rights(
        self,
        asset_id: str,
        verified_by: str | None = None,
        verification_method: str | None = None,
        evidence_urls: list[str] | None = None,
        notes: str | None = None,
    ) -> RightsVerification:
        """Mark rights as verified for an asset."""
        verification = RightsVerification(
            verification_id=f"verify-{uuid4().hex[:16]}",
            asset_id=asset_id,
            status=RightsStatus.VERIFIED,
            verified_by=verified_by,
            verified_at=datetime.now(UTC).isoformat(),
            verification_method=verification_method,
            evidence_urls=evidence_urls or [],
            notes=notes,
        )
        self._rights_cache[asset_id] = verification
        self._persist_rights()
        return verification

    def get_rights_verification(self, asset_id: str) -> RightsVerification | None:
        """Get rights verification status for an asset."""
        if asset_id in self._rights_cache:
            return self._rights_cache[asset_id]
        self._load_rights()
        return self._rights_cache.get(asset_id)

    def check_usage_rights(self, asset_id: str, commercial: bool = False) -> dict[str, Any]:
        """Check if an asset can be used for a specific purpose.

        Returns a dict with:
        - allowed: bool - whether usage is allowed
        - reason: str - explanation if not allowed
        - license: LicenseTerms - the license terms
        - verified: bool - whether rights are verified
        """
        license_terms = self.get_license(asset_id)
        rights = self.get_rights_verification(asset_id)

        result = {
            "allowed": True,
            "reason": None,
            "license": license_terms,
            "verified": rights is not None and rights.status == RightsStatus.VERIFIED,
        }

        if license_terms is None:
            result["allowed"] = False
            result["reason"] = "No license information available"
            return result

        if commercial and not license_terms.allows_commercial_use():
            result["allowed"] = False
            result["reason"] = f"License {license_terms.license_type} does not allow commercial use"
            return result

        if not license_terms.is_valid_at():
            result["allowed"] = False
            result["reason"] = "License has expired"
            return result

        return result

    def _persist_licenses(self) -> bool:
        """Persist license cache to disk."""
        try:
            data = {k: v.to_dict() for k, v in self._license_cache.items()}
            temporary = self.licenses_path.with_suffix(".json.tmp")
            temporary.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            os.replace(temporary, self.licenses_path)
            return True
        except (OSError, IOError):
            return False

    def _load_licenses(self) -> None:
        """Load licenses from disk."""
        if not self.licenses_path.exists():
            return
        try:
            data = json.loads(self.licenses_path.read_text(encoding="utf-8"))
            self._license_cache = {
                k: LicenseTerms.from_dict(v) for k, v in data.items()
            }
        except (json.JSONDecodeError, KeyError, ValueError):
            pass

    def _persist_rights(self) -> bool:
        """Persist rights cache to disk."""
        try:
            data = {k: v.to_dict() for k, v in self._rights_cache.items()}
            temporary = self.rights_path.with_suffix(".json.tmp")
            temporary.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            os.replace(temporary, self.rights_path)
            return True
        except (OSError, IOError):
            return False

    def _load_rights(self) -> None:
        """Load rights from disk."""
        if not self.rights_path.exists():
            return
        try:
            data = json.loads(self.rights_path.read_text(encoding="utf-8"))
            self._rights_cache = {
                k: RightsVerification.from_dict(v) for k, v in data.items()
            }
        except (json.JSONDecodeError, KeyError, ValueError):
            pass

    # Export/Import

    def export_provenance(
        self,
        asset_id: str | None = None,
        history_id: str | None = None,
        format: ProvenanceExportFormat = ProvenanceExportFormat.JSON,
    ) -> dict[str, Any] | str:
        """Export provenance records in various formats.

        Args:
            asset_id: Export provenance for a specific asset
            history_id: Export a specific history record
            format: Export format

        Returns:
            Provenance data in the requested format
        """
        if asset_id:
            lineage = self.get_asset_lineage(asset_id)
            records = [r.to_dict() for r in lineage]
            asset = self.get_asset(asset_id)
            data = {
                "asset_id": asset_id,
                "asset": asset.to_dict() if asset else None,
                "lineage": records,
                "export_format": format.value,
                "exported_at": datetime.now(UTC).isoformat(),
            }
        elif history_id:
            record = self.get_record(history_id)
            if record is None:
                raise ValueError(f"History record not found: {history_id}")
            data = {
                "history_id": history_id,
                "record": record.to_dict(),
                "export_format": format.value,
                "exported_at": datetime.now(UTC).isoformat(),
            }
        else:
            # Export all records
            records = self.list_history()
            data = {
                "records": [r.to_dict() for r in records],
                "export_format": format.value,
                "exported_at": datetime.now(UTC).isoformat(),
                "total_records": len(records),
            }

        if format == ProvenanceExportFormat.JSON:
            return data
        elif format == ProvenanceExportFormat.JSONL:
            lines = []
            for record in data.get("lineage", data.get("records", [data.get("record")])):
                if record:
                    lines.append(json.dumps(record, ensure_ascii=False))
            return "\n".join(lines)
        else:
            # For C2PA, IPTC, XMP - return structured data that can be embedded
            return data

    def import_provenance(self, data: dict[str, Any]) -> list[MediaHistoryRecord]:
        """Import provenance records.

        Args:
            data: Provenance data to import

        Returns:
            List of imported records
        """
        imported = []

        if "records" in data:
            # Multiple records
            for record_data in data["records"]:
                record = MediaHistoryRecord.from_dict(record_data)
                imported.append(record)
        elif "record" in data:
            # Single record
            record = MediaHistoryRecord.from_dict(data["record"])
            imported.append(record)
        elif "lineage" in data:
            # Lineage export
            for record_data in data["lineage"]:
                record = MediaHistoryRecord.from_dict(record_data)
                imported.append(record)

        # Merge with existing history
        existing = self.list_history()
        existing_ids = {r.history_id for r in existing}

        for record in imported:
            if record.history_id not in existing_ids:
                existing.append(record)

        # Persist merged history
        temporary = self.history_path.with_suffix(".json.tmp")
        temporary.write_text(
            json.dumps([r.to_dict() for r in existing], indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8"
        )
        os.replace(temporary, self.history_path)

        return imported

    # Integration with media_generation

    def create_generation_metadata(
        self,
        generation_id: str,
        prompt: str,
        model: str,
        provider_id: str,
        source: GenerationSource = GenerationSource.AI_GENERATED,
        **kwargs: Any,
    ) -> GenerationMetadata:
        """Create generation metadata for a media generation operation.

        This is a convenience method for integration with media_generation.py
        """
        return GenerationMetadata(
            generation_id=generation_id,
            source=source,
            prompt=prompt,
            prompt_hash=hashlib.sha256(prompt.encode("utf-8")).hexdigest(),
            model=model,
            provider_id=provider_id,
            generated_at=datetime.now(UTC).isoformat(),
            **kwargs,
        )

    @staticmethod
    def _safe_component(value: str, fallback: str) -> str:
        component = re.sub(r"[^A-Za-z0-9._-]+", "_", str(value)).strip("._-")
        return component[:120] or fallback
