class LicenseType(StrEnum):
    """Supported license types for media assets."""

    # Open source licenses
    CC0 = "cc0"  # Public domain dedication
    CC_BY = "cc-by"  # Attribution
    CC_BY_SA = "cc-by-sa"  # Attribution-ShareAlike
    CC_BY_NC = "cc-by-nc"  # Attribution-NonCommercial
    CC_BY_ND = "cc-by-nd"  # Attribution-NoDerivatives
    CC_BY_NC_SA = "cc-by-nc-sa"  # Attribution-NonCommercial-ShareAlike
    CC_BY_NC_ND = "cc-by-nc-nd"  # Attribution-NonCommercial-NoDerivatives
    MIT = "mit"  # MIT License
    APACHE_2 = "apache-2.0"  # Apache License 2.0
    GPL_3 = "gpl-3.0"  # GNU GPL v3
    BSD_3 = "bsd-3-clause"  # BSD 3-Clause

    # Proprietary/Commercial licenses
    PROPRIETARY = "proprietary"  # All rights reserved
    COMMERCIAL = "commercial"  # Commercial license
    ROYALTY_FREE = "royalty-free"  # Royalty-free license
    RIGHTS_MANAGED = "rights-managed"  # Rights-managed license

    # Custom/Other
    CUSTOM = "custom"  # Custom license terms
    UNKNOWN = "unknown"  # License not specified


class RightsStatus(StrEnum):
    """Status of rights verification for a media asset."""

    UNVERIFIED = "unverified"  # Not yet verified
    PENDING = "pending"  # Verification in progress
    VERIFIED = "verified"  # Rights verified
    DISPUTED = "disputed"  # Rights dispute raised
    REVOKED = "revoked"  # Rights revoked
    EXPIRED = "expired"  # License expired


